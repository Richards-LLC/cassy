use super::*;
use cas_store::TaskStore;
use std::process::Command;

fn git(repo: &Path, args: &[&str]) -> String {
    let out = Command::new("git")
        .args(args)
        .current_dir(repo)
        .env("GIT_AUTHOR_NAME", "report fixture")
        .env("GIT_AUTHOR_EMAIL", "fixture@example.test")
        .env("GIT_COMMITTER_NAME", "report fixture")
        .env("GIT_COMMITTER_EMAIL", "fixture@example.test")
        .output()
        .unwrap();
    assert!(out.status.success(), "{args:?}: {}", String::from_utf8_lossy(&out.stderr));
    String::from_utf8(out.stdout).unwrap().trim().into()
}

fn commit(repo: &Path, files: &[(&str, &str)]) -> String {
    for (path, body) in files {
        let path = repo.join(path);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, body).unwrap();
    }
    git(repo, &["add", "-A"]);
    git(repo, &["-c", "commit.gpgsign=false", "commit", "-qm", "fixture"]);
    git(repo, &["rev-parse", "HEAD"])
}

/// The GH #1627 report: an engineering dump on Google Fonts, no brief, no
/// brand tokens, no verdict, a table row per case naming task ids, about
/// 16,000 px tall. Visual QA passed it; the gate names every gap. The
/// shipped executive exemplar with its brief passes.
#[test]
fn report_gate_refuses_the_1627_dump_and_passes_the_exemplar_cas_5d07() {
    let repo = tempfile::tempdir().unwrap();
    git(repo.path(), &["init", "-q", "-b", "main"]);
    let base = commit(repo.path(), &[("README.md", "fixture\n")]);
    let db = tempfile::tempdir().unwrap();
    let store = cas_store::SqliteTaskStore::open(db.path()).unwrap();
    store.init().unwrap();
    let mut task = Task::new("cas-1234".into(), "Factory metrics report".into());
    store.add(&task).unwrap();
    let mut run = |task: &mut Task, head: &str| {
        let snapshot = task.clone();
        at_park(&mut CloseNoteTracker::new(&store, &snapshot), task, repo.path(), &base, None, Some(head), None)
    };

    let cases: String = (0..180)
        .map(|n| format!("<tr><td>cas-{:04x}</td><td>worker handoff latency</td><td>{n} min</td><td>supervisor relayed after the close gate</td></tr>", 0xa000 + n))
        .collect();
    let dump = format!(
        "<!doctype html><html><head><link rel=\"stylesheet\" href=\"https://fonts.googleapis.com/css2?family=Inter\">\
         <style>body{{font-family:Inter;color:#222;background:#fff}}</style></head><body>\
         <h1>Factory metrics: all 9 metrics, case by case</h1><p>Generated by the worker from cas-a001 notes.</p>\
         <h2>Cases</h2><table>{cases}</table></body></html>"
    );
    let head = commit(repo.path(), &[
        ("docs/reports/2026-11-06-factory-metrics.md", "# Factory metrics\n"),
        ("docs/reports/2026-11-06-factory-metrics.html", &dump),
    ]);
    let refusal = run(&mut task, &head).unwrap_err();
    for missing in [
        "REPORT NOT READY FOR THE OPERATOR",
        "docs/reports/2026-11-06-factory-metrics.html",
        "no concept brief",
        "brand tokens are not declared: --bg, --surface, --surface-hero, --ink, --line, --verdict, --evidence",
        "fetches from the network",
        "no verdict",
        "over the 4000 px budget for an executive reader",
        "internal task ids: cas-a000",
        "report quality waived:",
    ] {
        assert!(refusal.contains(missing), "missing `{missing}` in:\n{refusal}");
    }
    // A brief scored below the floor is named by dimension.
    let floor = crate::deliverable::report_quality::check(
        &dump,
        Some("Audience: executive\n\n## Critique\n\n| Dimension | Score | Evidence |\n| --- | --- | --- |\n| Distinctiveness | 1 | x |\n| Fit to argument | 2 | x |\n| Hierarchy | 1 | x |\n"),
    );
    assert!(floor.iter().any(|finding| finding.message.contains("distinctiveness 1, fit 2, hierarchy 1")), "{floor:?}");

    // A critique that skips a rubric dimension, or scores outside 1-5, is refused.
    let partial = crate::deliverable::report_quality::check(
        &dump,
        Some("Audience: executive\n\n## Critique\n\n| Dimension | Score | Evidence |\n| --- | --- | --- |\n| Distinctiveness | 5 | x |\n| Fit to argument | 9 | x |\n| Hierarchy | 5 | x |\n| Craft | 5 | x |\n"),
    );
    assert!(partial.iter().any(|finding| finding.message.contains("accessibility not scored") && finding.message.contains("fit 9 (scores run 1 to 5)")), "{partial:?}");

    let head = commit(repo.path(), &[
        ("docs/reports/2026-11-06-factory-metrics.html", include_str!("../../../../../../builtins/skills/cas-html-reports/references/examples/executive-variance-brief.html")),
        ("docs/reports/2026-11-06-factory-metrics.brief.md", include_str!("../../../../../../builtins/skills/cas-html-reports/references/examples/executive-variance-brief.why.md")),
    ]);
    assert_eq!(run(&mut task, &head), Ok(vec![]));
}
