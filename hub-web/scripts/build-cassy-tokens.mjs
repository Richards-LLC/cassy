#!/usr/bin/env node
// Build public/cassy-tokens.css: the Cassy Cloud token artifact (cas-eaa3).
//
// One source, two apps. docs/design/design-tokens.json generates
// src/tokens.css (the house roles); src/glass.css re-colours those roles for
// the Glass look. This script keeps only the custom-property blocks of both
// (scheme selectors and their media queries, no component rules) and writes
// them as one stylesheet Explorer can vendor. The hub serves it at
// /commander/cassy-tokens.css; scripts/sync-cassy-tokens.mjs copies and
// checks it. The header carries the SHA-256 of the body, so a copy can prove
// it is unedited and current.
//
//   node scripts/build-cassy-tokens.mjs           # write
//   node scripts/build-cassy-tokens.mjs --check   # exit 1 when stale
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const here = (path) => fileURLToPath(new URL(path, import.meta.url));
const { values } = parseArgs({ options: {
  tokens: { type: "string", default: here("../src/tokens.css") },
  glass: { type: "string", default: here("../src/glass.css") },
  output: { type: "string", default: here("../public/cassy-tokens.css") },
  check: { type: "boolean", default: false },
} });

/** Split CSS into top-level `{ prelude, body }` blocks; strings and parentheses are respected. */
export function blocks(css) {
  const out = [];
  let depth = 0, start = 0, open = -1, quote = null, paren = 0;
  for (let i = 0; i < css.length; i += 1) {
    const ch = css[i];
    if (quote) { if (ch === "\\") i += 1; else if (ch === quote) quote = null; continue; }
    if (ch === '"' || ch === "'") { quote = ch; continue; }
    if (ch === "(") paren += 1;
    else if (ch === ")") paren -= 1;
    else if (ch === "{" && paren === 0) { if (depth === 0) open = i; depth += 1; }
    else if (ch === "}" && paren === 0) {
      depth -= 1;
      if (depth < 0) throw new Error(`unbalanced } at ${i}`);
      if (depth === 0) { out.push({ prelude: css.slice(start, open).trim(), body: css.slice(open + 1, i) }); start = i + 1; }
    }
  }
  if (depth !== 0 || quote) throw new Error("unterminated block");
  return out;
}

/** Declarations of one rule body, split on top-level semicolons. */
function declarations(body) {
  const out = [];
  let quote = null, paren = 0, start = 0;
  for (let i = 0; i < body.length; i += 1) {
    const ch = body[i];
    if (quote) { if (ch === "\\") i += 1; else if (ch === quote) quote = null; continue; }
    if (ch === '"' || ch === "'") quote = ch;
    else if (ch === "(") paren += 1;
    else if (ch === ")") paren -= 1;
    else if (ch === ";" && paren === 0) { out.push(body.slice(start, i).trim()); start = i + 1; }
  }
  const tail = body.slice(start).trim();
  if (tail) out.push(tail);
  return out.filter(Boolean);
}

// A scheme selector names only the document: :root, html, attribute and :not() tests.
const SCHEME_PART = /^(?:html|:root)(?:\[[^\]]+\]|:root|:not\([^)]*\))*$/;
const schemeSelector = (prelude) => prelude.split(",").every((part) => SCHEME_PART.test(part.trim()));
const tokenDeclaration = (declaration) => /^--[\w-]+\s*:/.test(declaration) || /^color-scheme\s*:/.test(declaration);

function tokenRules(css) {
  const kept = [];
  for (const { prelude, body } of blocks(css.replace(/\/\*[\s\S]*?\*\//g, ""))) {
    if (prelude.startsWith("@media")) {
      const inner = tokenRules(body);
      if (inner.length) kept.push(`${prelude} {\n${inner.map((rule) => rule.replace(/^/gm, "  ")).join("\n")}\n}`);
    } else if (!prelude.startsWith("@") && schemeSelector(prelude)) {
      const decls = declarations(body);
      if (decls.length && decls.every(tokenDeclaration)) kept.push(`${prelude.replace(/\s+/g, " ")} {\n${decls.map((d) => `  ${d.replace(/\s*\n\s*/g, " ")};`).join("\n")}\n}`);
    }
  }
  return kept;
}

export function buildCassyTokens(tokensCss, glassCss) {
  const body = [
    "/* House roles (src/tokens.css) */",
    ...tokenRules(tokensCss),
    "/* Glass roles (src/glass.css) */",
    ...tokenRules(glassCss),
  ].join("\n") + "\n";
  const sha = createHash("sha256").update(body).digest("hex");
  const header = `/* Cassy Cloud design tokens. Generated by cassy hub-web/scripts/build-cassy-tokens.mjs; do not edit.
 * Source: docs/design/design-tokens.json -> hub-web/src/tokens.css + hub-web/src/glass.css (token blocks only).
 * Scheme: light by default, dark under prefers-color-scheme: dark; html[data-scheme="light"|"dark"] forces one.
 * Sync and check: node hub-web/scripts/sync-cassy-tokens.mjs (cassy hub-web/DESIGN.md "Shared tokens").
 * cassy-tokens-sha256: ${sha}
 */
`;
  return header + body;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    const css = buildCassyTokens(readFileSync(values.tokens, "utf8"), readFileSync(values.glass, "utf8"));
    if (values.check) {
      let current = "";
      try { current = readFileSync(values.output, "utf8"); } catch {}
      if (current !== css) { console.error(`${values.output} is stale; run node scripts/build-cassy-tokens.mjs`); process.exit(1); }
      console.log("cassy-tokens.css is current");
    } else {
      writeFileSync(values.output, css);
      console.log(`wrote ${values.output}`);
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(2);
  }
}
