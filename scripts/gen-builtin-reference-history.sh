#!/usr/bin/env bash
# Regenerate the shipped-builtin skill-file history ledger (cas-0c0a, cas-57c02).
#
# `sync_owned_reference` preserves any destination whose content does not match
# its recorded baseline, on the theory that it is a local customization. Files
# installed before the baseline ledger existed (Jul 2026) have no baseline at
# all, so pristine-but-old CAS content was misclassified as a local edit and
# skipped forever. This script embeds the SHA-256 of every *previously shipped*
# version of every builtin skill file (bodies, references, scripts, examples,
# templates) so sync and project Git reconciliation can tell "old CAS
# version" (safe to replace) apart from "someone edited this" (must preserve).
#
# Files Cassy has since deleted stay in the ledger: that is how sync proves an
# installed copy of a removed file is stale Cassy content and prunes it.
#
# Run after landing changes to any builtin skill file, and before cutting a
# release:
#
#   ./scripts/gen-builtin-reference-history.sh
#
# Output: cas-cli/src/builtins/reference-history.json (committed, embedded via
# include_str!).
#
# cas-2ea6: `--rev <revision> --output <file>` computes the ledger a fresh run
# would commit at <revision> (its history and tree, not the checkout) into
# <file>, read-only: no projection is rewritten. Repeat `--only <ledger key>`
# (for example skills/violet/SKILL.md) to compute only those keys' entries,
# which reads only their history. The close gate uses this to accept a target
# ledger whose dropped keys equal a fresh run.
set -euo pipefail

repo_root="$(git rev-parse --show-toplevel)"
cd "$repo_root"

out="cas-cli/src/builtins/reference-history.json"
rev=""
only=""
while [ $# -gt 0 ]; do
  case "$1" in
    --rev) rev=${2:?--rev needs a revision}; shift 2 ;;
    --output) out=${2:?--output needs a file}; shift 2 ;;
    --only) only+="${2:?--only needs a ledger key}"$'\n'; shift 2 ;;
    *) echo "usage: $0 [--rev <revision> --output <file> [--only <ledger key>]...]" >&2; exit 2 ;;
  esac
done
if [ -n "$only" ] && [ -z "$rev" ]; then
  echo "--only needs --rev and --output" >&2; exit 2
fi
if [ -n "$rev" ]; then
  git rev-parse --verify --quiet "$rev^{commit}" >/dev/null || { echo "unknown revision: $rev" >&2; exit 2; }
fi

# Keep the native Codex projection generated from the same verifier body as
# Claude/Grok. Role metadata never overrides the parent's security or account.
[ -n "$rev" ] || python3 - <<'PY'
from pathlib import Path
import tomllib

root = Path("cas-cli/src/builtins")
body = (root / "agents/task-verifier.body.md").read_text()
if "'''" in body:
    raise SystemExit("verifier body contains a TOML literal delimiter")
content = (
    '# managed_by: cas\n'
    '# Generated by scripts/gen-builtin-reference-history.sh; edit the shared verifier body.\n'
    'name = "task-verifier"\n'
    'description = "Review task completion independently; native role invocation grants no Cassy verification authority."\n'
    "developer_instructions = '''\n"
    "Native role discovery and invocation do not grant Cassy verification authority. "
    "Use only an authenticated dispatch supplied by the parent. If no legitimate "
    "handoff is available, return evidence to the supervisor for a registered "
    "independent reviewer; do not register yourself or manufacture authority.\n\n"
    + body + "\n'''\n"
)
tomllib.loads(content)
for target in [root / "codex/agents/task-verifier.toml", Path(".codex/agents/task-verifier.toml")]:
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists() or target.read_text() != content:
        target.write_text(content)
PY

# Collect the SHA-256 of every revision of every skill-owned file, in every
# harness flavour (claude sources live directly under builtins/, codex/grok
# under builtins/{codex,grok}/). Harness flavours share a builtin path on
# purpose: a destination holding another harness's shipped copy is still
# shipped CAS content, not a local edit. Source paths under a skill directory
# equal their install paths, so the flavour-stripped path is the key.
# Flat `skills/<name>.md` sources install at `skills/<name>/SKILL.md`.
# Include body history too: managed_by marks ownership, but cannot distinguish
# dirty output from a user edit that retained the marker (cas-9815).
#
# Two history walks feed the ledger:
#   1. One `git log -m --no-renames` pass over builtins/ lists the post-image
#      blob of every path in every commit, merges included (a version produced
#      by a conflict resolution exists in no ordinary commit, yet it shipped)
#      and deleted files included.
#   2. A `--follow` pass per current file adds the content it had under earlier
#      names, as the ledger always has. It skips merges: `--follow -m` costs
#      about 4x the runtime (the release gate runs this script) and a copy under
#      a file's old name is installed at the old path, which pass 1 covers.
# Blobs are hashed through one `git cat-file --batch`.
python3 - "$out" "$rev" "$only" <<'PY'
import hashlib
import json
import re
import subprocess
import sys

ROOT = "cas-cli/src/builtins/"
REV = [sys.argv[2]] if len(sys.argv) > 2 and sys.argv[2] else []
ONLY = set(filter(None, sys.argv[3].split("\n"))) if len(sys.argv) > 3 else set()
OWNED = re.compile(r"^(?:skills/[^/]+/.+|agents/task-verifier\.toml)$")
FLAT_BODY = re.compile(r"^skills/[^/]+\.md$")


def git(*args):
    return subprocess.run(["git", *args], capture_output=True, text=True, check=True).stdout


def key(source_path):
    path = source_path[len(ROOT):] if source_path.startswith(ROOT) else None
    if path is None:
        return None
    for flavour in ("codex/", "grok/"):
        if path.startswith(flavour):
            path = path[len(flavour):]
            break
    if FLAT_BODY.fullmatch(path):
        path = path[:-3] + "/SKILL.md"
    if not OWNED.match(path):
        return None
    return path


def post_image_blobs(raw_log):
    for line in raw_log.splitlines():
        if not line.startswith(":"):
            continue
        meta, _, path = line.partition("\t")
        blob = meta.split()[3]
        if blob.strip("0"):
            yield path, blob


def sources(ledger_key):
    """Every source path whose key() is ledger_key, in each harness flavour."""
    paths = [ledger_key]
    flat = re.fullmatch(r"(skills/[^/]+)/SKILL\.md", ledger_key)
    if flat:
        paths.append(flat.group(1) + ".md")
    return [ROOT + flavour + path for path in paths for flavour in ("", "codex/", "grok/")]


pathspecs = [path for ledger_key in sorted(ONLY) for path in sources(ledger_key)] if ONLY else [ROOT]
pairs = set()
for path, blob in post_image_blobs(
    git("log", "-m", "--no-renames", "--raw", "--no-abbrev", "--format=", *REV, "--", *pathspecs)
):
    builtin_path = key(path)
    if builtin_path:
        pairs.add((builtin_path, blob))

tracked = git("ls-tree", "-r", "--name-only", REV[0], "--", ROOT) if REV else git("ls-files", "--", ROOT)
for source_path in tracked.splitlines():
    builtin_path = key(source_path)
    if not builtin_path or ONLY and builtin_path not in ONLY:
        continue
    for _, blob in post_image_blobs(
        git("log", "--follow", "--raw", "--no-abbrev", "--format=", *REV, "--", source_path)
    ):
        pairs.add((builtin_path, blob))

blobs = sorted({blob for _, blob in pairs})
batch = subprocess.run(
    ["git", "cat-file", "--batch"],
    input="".join(f"{blob}\n" for blob in blobs).encode(),
    capture_output=True,
    check=True,
).stdout
digests = {}
offset = 0
for blob in blobs:
    newline = batch.index(b"\n", offset)
    name, kind, size = batch[offset:newline].decode().split()
    if name != blob or kind != "blob":
        sys.exit(f"unexpected cat-file header for {blob}: {name} {kind}")
    start = newline + 1
    digests[blob] = hashlib.sha256(batch[start:start + int(size)]).hexdigest()
    offset = start + int(size) + 1

files = {}
for builtin_path, blob in pairs:
    files.setdefault(builtin_path, set()).add(digests[blob])
doc = {
    "version": 1,
    "comment": "Generated by scripts/gen-builtin-reference-history.sh - SHA-256 of every previously shipped version of each builtin skill file, including bodies. Do not hand-edit.",
    "files": {path: sorted(hashes) for path, hashes in sorted(files.items())},
}
with open(sys.argv[1], "w") as handle:
    handle.write(json.dumps(doc, indent=2) + "\n")
PY

echo "wrote $out ($(wc -c <"$out") bytes)"
